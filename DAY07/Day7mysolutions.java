//Pattern 1: Inverted Right-angled triangle
import java.util.Scanner;
class Hello{
public static void main(String args[]){
  Scanner sc=new Scanner(System.in);
  int n=sc.nextInt();
  int k=n;
  for(int i=0;i<k;i++){
    for(int j=0;j<n;j++)
      {
        System.out.print("*");
      }
      n--;
      System.out.println();
    }
    
  }
  }
